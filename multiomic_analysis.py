def _detect_cols_expanded(df: pd.DataFrame) -> Dict[str, Optional[str]]:
    cols = set(df.columns)
    def has_any(opts: List[str]) -> Optional[str]:
        for c in opts:
            if c in cols: return c
        return None
    return dict(
        symbol = has_any(["Gene","symbol","Symbol","Hugo_Symbol","HUGO","HugoSymbol","Gene_Symbol","gene_symbol"]),
        ensg   = has_any(["ENSGene_core","ENSGene","ENSG","ensembl_gene_id","Ensembl","Ensembl_ID"]),
        rna_t  = has_any(["RNA_Count"]),
        rna_n  = has_any(["Normal_RNA_Count"]),
        cn_t   = has_any(["copy_number","CNV_Count"]),
        cn_n   = has_any(["Normal_copy_number","Normal_CNV_Count"]),
        ch3_t  = has_any(["CH3_Beta"]),
        ch3_n  = has_any(["Normal_CH3_Beta"]),
        pro_t  = has_any(["SEQ","Protein_SEQ"]),
        pro_n  = has_any(["Normal_SEQ","Normal_Protein_SEQ"]),
        pro_int_t = has_any(["INT","Protein_INT","Ion_T","Ion"]),
        pro_int_n = has_any(["Normal-INT","Normal_INT","Ion-Normal","Ion_Normal","Normal_Protein_INT"]),
        info   = has_any(["INFO","Info","info"]),
    )

def _validate_refs(refs: dict, strict: bool = False) -> None:
    """
    Check that optional reference files exist.
    - If strict=True, raise FileNotFoundError when any referenced file is missing.
    - If strict=False, just log a warning and continue.
    """
    missing = []
    for key in ("lung_tsv", "gene_reads"):
        p = refs.get(key)
        if p is not None and str(p).strip() != "" and not Path(str(p)).exists():
            missing.append((key, p))

    if missing:
        msg = "; ".join([f"{k}={v}" for k, v in missing])
        if strict:
            raise FileNotFoundError(f"Strict refs: missing files: {msg}")
        else:
            logging.warning(f"[refs] Missing optional references (continuing): {msg}")


